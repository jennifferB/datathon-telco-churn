USE ROLE ACCOUNTADMIN;

CREATE WAREHOUSE IF NOT EXISTS COMPUTE_WH WITH WAREHOUSE_SIZE = 'X-SMALL';
USE WAREHOUSE COMPUTE_WH;

CREATE DATABASE IF NOT EXISTS TELCO_G2;
CREATE SCHEMA IF NOT EXISTS TELCO_G2.ANALYTICS;

-- Roles
CREATE ROLE IF NOT EXISTS TELCO_WRITER;
CREATE ROLE IF NOT EXISTS TELCO_READER;

-- Permisos de lectura (Steward y Analyst)
GRANT USAGE ON DATABASE TELCO_G2 TO ROLE TELCO_READER;
GRANT USAGE ON SCHEMA TELCO_G2.ANALYTICS TO ROLE TELCO_READER;
GRANT SELECT ON ALL TABLES IN SCHEMA TELCO_G2.ANALYTICS TO ROLE TELCO_READER;
GRANT SELECT ON FUTURE TABLES IN SCHEMA TELCO_G2.ANALYTICS TO ROLE TELCO_READER;
GRANT USAGE ON WAREHOUSE COMPUTE_WH TO ROLE TELCO_READER;

-- Permisos de escritura (Engineer): incluye todo lo anterior
GRANT ROLE TELCO_READER TO ROLE TELCO_WRITER;
GRANT CREATE TABLE ON SCHEMA TELCO_G2.ANALYTICS TO ROLE TELCO_WRITER;
GRANT INSERT, UPDATE, DELETE, TRUNCATE ON ALL TABLES IN SCHEMA TELCO_G2.ANALYTICS TO ROLE TELCO_WRITER;
GRANT INSERT, UPDATE, DELETE, TRUNCATE ON FUTURE TABLES IN SCHEMA TELCO_G2.ANALYTICS TO ROLE TELCO_WRITER;

-- Usuarios (recuerda cambiar las contraseñas temporales aquí abajo)
CREATE USER IF NOT EXISTS engineer_telco PASSWORD='Telco2026#Eng' MUST_CHANGE_PASSWORD=TRUE DEFAULT_ROLE=TELCO_WRITER DEFAULT_WAREHOUSE=COMPUTE_WH;
CREATE USER IF NOT EXISTS steward_telco  PASSWORD='Telco2026#Stw' MUST_CHANGE_PASSWORD=TRUE DEFAULT_ROLE=TELCO_READER DEFAULT_WAREHOUSE=COMPUTE_WH;
CREATE USER IF NOT EXISTS analyst_telco  PASSWORD='Telco2026#Ana' MUST_CHANGE_PASSWORD=TRUE DEFAULT_ROLE=TELCO_READER DEFAULT_WAREHOUSE=COMPUTE_WH;

GRANT ROLE TELCO_WRITER TO USER engineer_telco;
GRANT ROLE TELCO_READER TO USER steward_telco;
GRANT ROLE TELCO_READER TO USER analyst_telco;

-- Comprobación 
SHOW USERS LIKE '%telco%';
SHOW GRANTS TO ROLE TELCO_READER;
SHOW GRANTS TO ROLE TELCO_WRITER;



